export const translateWidgetText = (text, language) => {
  const dictionary = language === 'es' ? spanishText : language === 'fr' ? frenchText : null
  const notices = language === 'fr' ? frenchServiceTranslations : serviceTranslations
  if (!dictionary) return text
  if (Object.hasOwn(notices, text)) return notices[text]
  return Object.hasOwn(dictionary, text) ? dictionary[text] : text
}

export const loadWidgetLanguage = () => {
  try {
    const language = localStorage.getItem('chatbot_language')
    return ['en', 'es', 'fr'].includes(language) ? language : 'en'
  } catch {
    return 'en'
  }
}
