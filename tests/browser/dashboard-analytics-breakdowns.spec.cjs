const { test, expect } = require('@playwright/test');
const { buildMonthlyAnalytics } = require('../../server/lib/monthly-analytics');

test('breakdown panels show top five by default, expand independently, and reset when changing months', async ({ page }) => {
  const rows = Array.from({ length: 8 }, (_, index) => ({ key: `topic_${index + 1}`, count: 8 - index }));
  const data = buildMonthlyAnalytics([], { startMonth: '2026-01', endMonth: '2026-02' });
  Object.assign(data.totals, { userMessages: 36, categories: rows, rules: rows, responseTypes: rows.slice(0, 3) });
  Object.assign(data.months[0], { userMessages: 36, categories: rows, rules: rows, responseTypes: rows.slice(0, 3) });
  await page.addInitScript(() => sessionStorage.setItem('dashboard_token', 'test-dashboard-token'));
  await page.route('**/api/**', (route) => route.fulfill({ json: route.request().url().includes('/monthly-analytics') ? data : {} }));
  await page.goto('./dashboard');
  await page.getByRole('tab', { name: 'Monthly analytics', exact: true }).click();
  await page.locator('.dashboard-sidebar').getByRole('link', { name: 'Usage & referrals', exact: true }).click();
  await page.getByRole('tab', { name: 'Topics & rules', exact: true }).click();
  const categories = page.getByRole('region', { name: 'Question categories', exact: true });
  const rules = page.getByRole('region', { name: 'Rules used', exact: true });
  const replies = page.getByRole('region', { name: 'Types of replies', exact: true });
  await expect(categories.getByRole('listitem')).toHaveCount(5);
  await expect(rules.getByRole('listitem')).toHaveCount(5);
  await expect(replies.getByRole('listitem')).toHaveCount(3);
  await expect(replies.getByRole('button')).toHaveCount(0);
  await categories.getByRole('button', { name: 'Show all (8)', exact: true }).click();
  await expect(categories.getByRole('listitem')).toHaveCount(8);
  await expect(categories.getByRole('button', { name: 'Show top five', exact: true })).toHaveAttribute('aria-expanded', 'true');
  await expect(rules.getByRole('listitem')).toHaveCount(5);
  await rules.getByRole('button', { name: 'Show all (8)', exact: true }).click();
  await expect(rules.getByRole('listitem')).toHaveCount(8);
  await categories.getByRole('button', { name: 'Show top five', exact: true }).click();
  await expect(categories.getByRole('listitem')).toHaveCount(5);
  await page.getByRole('combobox', { name: 'Show details for', exact: true }).selectOption('2026-01');
  await expect(rules.getByRole('listitem')).toHaveCount(5);
  await page.getByRole('combobox', { name: 'Show details for', exact: true }).selectOption('2026-02');
  await expect(categories).toContainText('No questions recorded.');
  await expect(categories.getByRole('button')).toHaveCount(0);
  await page.getByRole('combobox', { name: 'Show details for', exact: true }).selectOption('all');
  await expect(categories.getByRole('listitem')).toHaveCount(5);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.locator('.analytics-breakdown-grid').screenshot({ path: `/tmp/analytics-breakdowns-${page.viewportSize().width}.png` });
});
